// reference : https://utb.sakura.ne.jp/blog/archives/39
static bool process_jp_symbols_impl(uint16_t keycode, bool pressed) {
    if (!pressed) {
        return true;
    }
    uint8_t shift = keyboard_report->mods & (MOD_BIT(KC_LSFT) | MOD_BIT(KC_RSFT));
    if (!shift) {
        return true;
    }
    uint16_t s;
    switch (keycode) {
        // Replace Shift-Symbols like ANSI for JIS.
        // Shift中に押された場合、JISの記号に置き換える
        // (same as ANSI) case JP_1:    s = JP_EXLM; break; // Shift+1 = !
        case JP_2:    s = JP_AT; break;
        // (same as ANSI) case JP_3:    s = JP_HASH; break; // Shift+3 = #
        // (same as ANSI) case JP_4:    s = JP_DLR; break; // Shift+4
        // (same as ANSI) case JP_5:    s = JP_PERC; break; // Shift+5 = %
        case JP_6:    s = JP_CIRC; break; // Shift+6 = ^
        case JP_7:    s = JP_AMPR; break; // Shift+7 = &
        case JP_8:    s = JP_ASTR; break; // Shift+8 = *
        case JP_9:    s = JP_LPRN; break; // Shift+9 = (
        case JP_0:    s = JP_RPRN; break; // Shift+0 = )
        case JP_EQL:  s = JP_PLUS; break; // Shift+= = +
        case JP_MINS: s = JP_UNDS; break; // Shift+- = _
        case JP_QUOT: s = JP_DQUO; break; // Shift+' = "
        case JP_SCLN: s = JP_COLN; break; // Shift+; = :
        //case JP_ZKHK: s = JP_TILD; break; // Shift+\\ = |
        case JP_GRV: s = JP_TILD; break; // Shift+` = ~
        case JP_BSLS: s = JP_PIPE; break; // Shift+\ = |
        default: return true;
    }
    unregister_mods(shift);
    tap_code16(s);
    register_mods(shift);
    return false;
}

bool process_jp_symbols(uint16_t keycode, keyrecord_t *record) {
    return process_jp_symbols_impl(keycode, record->event.pressed);
}

void tap_code16jp(uint16_t keycode) {
    if (process_jp_symbols_impl(keycode, true)) {
        tap_code16(keycode);
    }
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    return process_jp_symbols(keycode, record);
}
